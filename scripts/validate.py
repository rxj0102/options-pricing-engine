"""Numerical validation of the pricing engine against known values and identities.

Writes results/validation.json and renders the README Validation block.

    python scripts/validate.py           # run checks, rewrite README block
    python scripts/validate.py --check   # exit 1 if README is out of date with results/
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from greeks import BSMGreeks, NumericalGreeks  # noqa: E402
from pricing import Black76, BlackScholesMerton, BoyleTrinomial, CRRBinomial, OptionContract  # noqa: E402
from validation import ConvergenceAnalyzer  # noqa: E402

RES = ROOT / "results"
START = "<!-- validation:start (generated by scripts/validate.py, do not edit by hand) -->"
END = "<!-- validation:end -->"
S, K, T, R, SIG = 100.0, 100.0, 1.0, 0.05, 0.20


def compute() -> dict:
    t0 = time.time()
    bsm = BlackScholesMerton()
    call = bsm.price(S, K, T, R, SIG, "call")
    put = bsm.price(S, K, T, R, SIG, "put")
    out = {
        "bsm_call": call,
        "bsm_put": put,
        "parity_error": abs((call - put) - (S - K * np.exp(-R * T))),
        "black76_from_spot": Black76().price_from_spot(S, K, T, R, SIG),
        "implied_vol_roundtrip": bsm.implied_vol(call, S, K, T, R),
        "crr_1000": CRRBinomial(1000).price(S, K, T, R, SIG, "call"),
        "trinomial_1000": BoyleTrinomial(1000).price(S, K, T, R, SIG, "call"),
        "american_put_crr_2000": CRRBinomial(2000).price(S, K, T, R, SIG, "put", exercise_style="american"),
    }
    out["early_exercise_premium"] = out["american_put_crr_2000"] - put
    a = BSMGreeks().compute(S, K, T, R, SIG, "call")
    n = NumericalGreeks(bsm).compute(S, K, T, R, SIG)
    out["greek_max_abs_diff"] = max(abs(getattr(a, g) - getattr(n, g)) for g in ("delta", "gamma", "vega", "theta", "rho"))
    conv = ConvergenceAnalyzer().analyze(OptionContract(S=S, K=K, T=T, r=R, q=0.0, sigma=SIG))
    out["binomial_order"] = conv["binomial_order"]
    out["trinomial_order"] = conv["trinomial_order"]
    out["runtime_seconds"] = round(time.time() - t0)
    out = {k: float(v) for k, v in out.items()}
    RES.mkdir(exist_ok=True)
    (RES / "validation.json").write_text(json.dumps(out, indent=2))
    return out


def render(v: dict) -> str:
    rows = [
        ("Black-Scholes call, S = K = 100, T = 1, r = 5%, sigma = 20%", "10.4506 (closed form)", f"{v['bsm_call']:.4f}"),
        ("Put-call parity, C - P - (S - K e^(-rT))", "0", f"{v['parity_error']:.1e}"),
        ("Black-76 priced from spot", "equal to Black-Scholes", f"{v['black76_from_spot']:.4f}"),
        ("Implied vol round trip", "0.2", f"{v['implied_vol_roundtrip']:.6f}"),
        ("CRR binomial, 1,000 steps", "converges to Black-Scholes", f"{v['crr_1000']:.4f} (error {v['crr_1000'] - v['bsm_call']:+.4f})"),
        ("Boyle trinomial, 1,000 steps", "converges to Black-Scholes", f"{v['trinomial_1000']:.4f} (error {v['trinomial_1000'] - v['bsm_call']:+.4f})"),
        ("Empirical convergence order, binomial / trinomial", "about 1", f"{v['binomial_order']:.2f} / {v['trinomial_order']:.2f}"),
        ("American put early exercise premium (CRR 2,000 steps minus European put)", "positive", f"{v['early_exercise_premium']:.4f} ({v['american_put_crr_2000']:.4f} vs {v['bsm_put']:.4f})"),
        ("Analytical vs finite-difference Greeks (delta, gamma, vega, theta, rho)", "below 1e-4", f"max difference {v['greek_max_abs_diff']:.1e}"),
    ]
    o = ["| Check | Expected | Result |", "|---|---|---|"] + [f"| {a} | {b} | {c} |" for a, b, c in rows]
    took = "under a second" if v["runtime_seconds"] < 1 else f"about {v['runtime_seconds']:.0f} seconds"
    o += ["", f"All checks run in {took} (`make validate`)."]
    return "\n".join(o)


def main() -> None:
    readme = ROOT / "README.md"
    text = readme.read_text()
    pre, rest = text.split(START, 1)
    _, post = rest.split(END, 1)
    if "--check" in sys.argv:
        v = json.loads((RES / "validation.json").read_text())
        if pre + START + "\n" + render(v) + "\n" + END + post != text:
            sys.exit("README Validation block is out of date. Run: python scripts/validate.py")
        print("README Validation block matches results/")
        return
    v = compute()
    readme.write_text(pre + START + "\n" + render(v) + "\n" + END + post)
    print(render(v))


if __name__ == "__main__":
    main()
